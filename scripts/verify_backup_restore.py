"""Restore a backup into an owned disposable database and compare its contents."""

from __future__ import annotations

import argparse
import gzip
import hashlib
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
from uuid import uuid4

from sqlalchemy import MetaData, Table, create_engine, func, inspect, select
from sqlalchemy.engine import Engine, make_url


def database_manifest(engine: Engine) -> dict[str, tuple[tuple[str, ...], int, str]]:
    """Compare schema, row counts, and deterministic primary-key samples."""
    manifest = {}
    with engine.connect() as connection:
        for name in sorted(inspect(connection).get_table_names()):
            table = Table(name, MetaData(), autoload_with=connection)
            count = connection.scalar(select(func.count()).select_from(table))
            primary_key = list(table.primary_key.columns)
            sample = (
                connection.execute(select(table).order_by(*primary_key).limit(5)).all()
                if primary_key else []
            )
            digest = hashlib.sha256(repr(sample).encode("utf-8")).hexdigest()
            manifest[name] = (tuple(table.columns.keys()), int(count or 0), digest)
    if not manifest:
        raise RuntimeError("Source or restored database contains no tables.")
    return manifest


def _postgres_command(command: list[str], password: str | None) -> None:
    environment = dict(os.environ)
    if password is not None:
        environment["PGPASSWORD"] = password
    result = subprocess.run(
        command, env=environment, capture_output=True, text=True, check=False
    )
    if result.returncode:
        # Do not echo connection arguments or provider stderr containing credentials.
        raise RuntimeError(
            f"{command[0]} failed with exit code {result.returncode} during recovery drill."
        )


def verify_restore(source_url: str, archive: Path) -> int:
    """Never accepts a restore target: every target is generated by this drill."""
    archive = archive.resolve(strict=True)
    source = make_url(source_url)
    if source.get_backend_name() not in {"sqlite", "postgresql"}:
        raise ValueError("Recovery drill supports SQLite and PostgreSQL only.")
    if source.get_backend_name() == "sqlite":
        if not source.database or source.database == ":memory:":
            raise ValueError("Recovery drill requires an existing SQLite file.")
        source_file = Path(source.database).resolve(strict=True)
        source = source.set(database=f"file:{source_file.as_posix()}").update_query_dict(
            {"mode": "ro", "uri": "true"}
        )
    source_engine = create_engine(source)
    try:
        expected = database_manifest(source_engine)
    finally:
        source_engine.dispose()

    with tempfile.TemporaryDirectory(prefix="ffpi-recovery-") as directory:
        restored_file = Path(directory) / "restored.db"
        with archive.open("rb") as raw:
            if archive.suffix == ".gz":
                with gzip.GzipFile(fileobj=raw) as compressed, restored_file.open("wb") as target:
                    shutil.copyfileobj(compressed, target)
            else:
                with restored_file.open("wb") as target:
                    shutil.copyfileobj(raw, target)

        if source.get_backend_name() == "sqlite":
            restored_engine = create_engine(f"sqlite:///{restored_file.as_posix()}")
            try:
                actual = database_manifest(restored_engine)
            finally:
                restored_engine.dispose()
        else:
            database_name = f"ffpi_recovery_{uuid4().hex}"
            restored_url = source.set(database=database_name)
            admin_url = source.set(database="postgres")._replace(password=None).render_as_string(hide_password=False)
            target_url = restored_url._replace(password=None).render_as_string(hide_password=False)
            # PostgreSQL CLI tools use libpq URLs, not SQLAlchemy driver names.
            admin_url = admin_url.replace(source.drivername + ":", "postgresql:", 1)
            target_url = target_url.replace(source.drivername + ":", "postgresql:", 1)
            created = False
            try:
                _postgres_command(["createdb", "--maintenance-db", admin_url, database_name], source.password)
                created = True
                _postgres_command([
                    "pg_restore", "--exit-on-error", "--no-owner", "--no-privileges",
                    "--dbname", target_url, str(restored_file),
                ], source.password)
                restored_engine = create_engine(restored_url)
                try:
                    actual = database_manifest(restored_engine)
                finally:
                    restored_engine.dispose()
            finally:
                if created:
                    _postgres_command([
                        "dropdb", "--maintenance-db", admin_url, database_name,
                    ], source.password)

    if expected != actual:
        raise RuntimeError(
            "Restored database differs from source schema, row counts, or sampled data. "
            "Run against a quiescent source or investigate the archive."
        )
    return len(actual)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--archive", required=True, type=Path)
    args = parser.parse_args()
    source_url = os.environ.get("DB_URL") or os.environ.get("DATABASE_URL")
    if not source_url:
        parser.error("DB_URL or DATABASE_URL is required.")
    try:
        tables = verify_restore(source_url, args.archive)
    except (RuntimeError, FileNotFoundError, gzip.BadGzipFile) as exc:
        print(f"Recovery drill FAILED: {exc}")
        return 1
    except Exception as exc:
        # SQLAlchemy exceptions can embed connection strings and SQL parameters.
        print(f"Recovery drill FAILED ({type(exc).__name__}); no existing database was a restore target.")
        return 1
    print(f"Recovery drill PASS: restored and verified {tables} tables in an isolated database.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
